// Package wasmbridge builds the in-process path that actually wins: a Go module compiled to
// WebAssembly with a reactor entry point, called from JavaScript as an ordinary function.
//
// It exists because two other designs were measured and rejected: cgo plus N-API costs 215 ns a call
// (the cgo ABI is 40–60 ns of it before any work), and a shared-memory ring costs 182 ns even between
// two JavaScript threads. A wasm call is neither: it is a function call into the same address space,
// 18 ns for a leaf port and about 120 ns for one that allocates.
//
// The one thing that matters and cost a day to find: `-buildmode=c-shared`. Without it, a wasip1 module
// is a command — it initialises in `_start` and every export aborts with "notInitialized". With it, the
// module is a reactor, real Go runs inside the exports, and `//go:wasmexport` is the whole interface.
package wasmbridge

import (
	"fmt"
	"go/ast"
	goparser "go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/xiaobingan/go-anything/internal/jswire"

	"github.com/xiaobingan/go-anything/internal/toolchain"
)

// Scratch is the layout both sides agree on: the caller writes the name and arguments at the base,
// the module writes the reply 64 KiB further in, and nothing else is shared.
const (
	ScratchSize = 128 << 10
	ReplyOffset = 64 << 10
)

// Export is one function the module answers, with the shape its arguments and reply have.
type Export struct {
	Name    string
	Params  []string
	Returns string
}

// Options is one wasm build.
type Options struct {
	CrateDir string
	Crate    string
	Exports  []string
	// Typed carries the signature of each export, so a direct entry can be generated per shape. An
	// export whose shape is not in the list still answers through the generic JSON call.
	Typed []Export
	// LeaveTinyGo is for the day the toolchain here has no wasm target: it writes the sources and says
	// what to run, instead of failing halfway.
	LeaveTinyGo bool
}

// module is the Go side: two exports, one scratch buffer, and the same Answer the other bridges use.
const module = `// Command portwasm is the in-process port as a WebAssembly reactor.
//
//	GOOS=wasip1 GOARCH=wasm go build -buildmode=c-shared -o port.wasm ./cmd/portwasm
//
// The caller writes the export name and its JSON arguments into the scratch buffer, calls go_call, and
// reads the reply from the second half of the same buffer. No pipe, no cgo, no N-API — the call crosses
// nothing at all.
package main

import (
	"encoding/json"
	"unsafe"

	port "` + cratePlaceholder + `"
)

const (
	scratchSize = 128 << 10
	replyOffset = 64 << 10
)

// scratch is the shared buffer: [0, 64 KiB) for the request, [64 KiB, 128 KiB) for the reply.
var scratch [scratchSize]byte

//go:wasmexport go_scratch
func goScratch() uint32 {
	return uint32(uintptr(unsafe.Pointer(&scratch[0])))
}

//go:wasmexport go_call
//
// Answers one call: the reply is written at ReplyOffset and its length is returned, or 0 when the
// request does not fit or the port failed in a way it cannot report.
func goCall(nameLen uint32, argsLen uint32) uint32 {
	name := byteString(&scratch[0], nameLen)
	args := byteString(&scratch[nameLen], argsLen)
	reply := port.AnswerJSON(name, args)
	if uint32(len(reply)) > uint32(len(scratch)-replyOffset) {
		return 0
	}
	copy(scratch[replyOffset:], reply)
	return uint32(len(reply))
}

%DIRECT%

//go:wasmexport go_call1
//
// The one-string call: the argument is the string itself, not JSON, and the reply is the value's JSON
// only (no {"ok":…} envelope). Most ports are this shape, and skipping the encode is most of the win.
func goCall1(nameLen uint32, argLen uint32) uint32 {
	name := byteString(&scratch[0], nameLen)
	arg := byteString(&scratch[nameLen], argLen)
	fn, ok := port.Registry[name]
	if !ok {
		return 0
	}
	v, err := fn([]any{arg})
	var reply []byte
	if err != nil {
		reply, _ = json.Marshal(err.Error())
	} else {
		b, err := json.Marshal(v)
		if err != nil {
			return 0
		}
		reply = b
	}
	if uint32(len(reply)) > uint32(len(scratch)-replyOffset) {
		return 0
	}
	copy(scratch[replyOffset:], reply)
	return uint32(len(reply))
}

// byteString reads n bytes as a string without copying: the bytes live in this module's memory and the
// port only reads them.
func byteString(p *byte, n uint32) string {
	if n == 0 {
		return ""
	}
	return unsafe.String(p, int(n))
}

func main() {}
`

// wrapper is the JavaScript side: one wasm instance, one scratch buffer, one call per invocation.
const wrapper = `// Generated by go-anything: the port as WebAssembly, called in-process.
//
//   import port from './index.wasm.mjs'
//   port.count('a b  ')          // 2
//   port.raw('count', '["a b  "]')  // the JSON reply, for the cases the typed path cannot carry
//
// There is no child process and no addon: the module is a reactor, initialised once, and a call is a
// function call into the same address space.
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { WASI } from 'node:wasi'

const here = new URL('.', import.meta.url)
const bytes = await readFile(new URL('port.wasm', here))

// A reactor needs no argv or environment, and it must not be started: ` + "`initialize`" + ` runs the
// module's init without running main to completion.
const wasi = new WASI({ version: 'preview1', args: [], env: {} })
const { instance } = await WebAssembly.instantiate(bytes, wasi.getImportObject())
try {
  wasi.initialize(instance)
} catch (e) {
  if (!String(e.message).includes('already initialized')) throw e
}

const exports = instance.exports

// The Go runtime grows its memory, and growing detaches the old view: keep the view and refresh it
// when the buffer it points at is gone.
let memory = new Uint8Array(exports.memory.buffer)
function view() {
  if (memory.buffer.byteLength === 0) memory = new Uint8Array(exports.memory.buffer)
  return memory
}
const scratch = exports.go_scratch()
const encoder = new TextEncoder()
const decoder = new TextDecoder()

%JSWIRE_ENCODE%

%JSWIRE_DECODE%

// raw answers one call with the export name and an arguments array already encoded as JSON.
function raw(name, argsJSON) {
  const nameBytes = encoder.encode(name)
  const argBytes = encoder.encode(argsJSON)
  if (nameBytes.length + argBytes.length >= %REPLY_OFFSET%) {
    throw new Error('go-anything: request larger than the scratch buffer')
  }
  const mem = view()
  mem.set(nameBytes, scratch)
  mem.set(argBytes, scratch + nameBytes.length)
  const len = exports.go_call(nameBytes.length, argBytes.length)
  if (len === 0) throw new Error('go-anything: ' + name + ' failed')
  const text = decoder.decode(view().subarray(scratch + %REPLY_OFFSET%, scratch + %REPLY_OFFSET% + len))
  const reply = JSON.parse(text)
  if (reply.error) throw new Error(reply.error)
  if (reply.panic) throw new Error('Go panic: ' + reply.panic)
  return reply.ok
}

// A call with one string argument takes the fast path: the name's bytes are encoded once at load, the
// argument is written straight into the module's memory, and the reply is the value's JSON.
const names = new Map(%EXPORTS%.map(name => [name, encoder.encode(name)]))
const call1 = exports.go_call1
// One reusable view over the argument area, refreshed when the runtime grows its memory.
let argArea = null
function argView() {
  const mem = view()
  if (argArea === null || argArea.buffer !== mem.buffer) {
    argArea = mem.subarray(scratch, scratch + (%REPLY_OFFSET% - 1024))
  }
  return argArea
}

function fast(name, arg) {
  const nameBytes = names.get(name)
  const area = argView()
  // Write the name into the same area, then the argument right after it: one encoding, one call.
  area.set(nameBytes, 0)
  const written = encoder.encodeInto(arg, area.subarray(nameBytes.length))
  if (written.read !== arg.length) return raw(name, JSON.stringify([arg]))
  const len = call1(nameBytes.length, written.written)
  if (len === 0) throw new Error('go-anything: ' + name + ' failed')
  return JSON.parse(decoder.decode(view().subarray(scratch + %REPLY_OFFSET%, scratch + %REPLY_OFFSET% + len)))
}

// Direct entries: a generated export per signature, so a call is one function call into the module
// with no registry lookup, no boxing and no Marshal.
const DIRECT = %DIRECT_MAP%

const port = { raw, direct: Object.keys(DIRECT).length > 0 }
for (const name of %EXPORTS%) {
  port[name] = (...args) => {
    if (DIRECT[name] && args.length === 1 && typeof args[0] === 'string') {
      return DIRECT[name](args[0])
    }
    if (args.length === 1 && typeof args[0] === 'string' && call1) {
      try {
        return decode(fast(name, args[0]))
      } catch (e) {
        return decode(raw(name, JSON.stringify(encode(args)))) // fall back for a payload the fast path cannot hold
      }
    }
    return decode(raw(name, JSON.stringify(encode(args))))
  }
}
export default port
`

const cratePlaceholder = "__CRATE__"

// crateSupport is written into the port package: one function per shape, calling the port's own
// function directly. It lives beside port.go so it can reach the unexported functions; the wasm module
// is package main and can only call exported ones.
const crateSupport = `// Typed entry points for the WebAssembly module, generated by go-anything.
//
// Each one calls the port's function directly: no registry lookup, no []any for the reply, and a
// number comes back as a number. Regenerate with ` + "`go-anything wasm`" + `.
package port

import (
%MATH%%STRCONV%	"fmt"
	"unsafe"
)

// portCall answers an export through the registry, which every crate has: the generated WebAssembly
// module must compile for a port written in the scaffold's own shape as well as for a typed one.
func portCall(name string, args []any) (any, error) {
	fn, ok := Registry[name]
	if !ok {
		return nil, fmt.Errorf("not ported: %s", name)
	}
	return fn(args)
}

// bytesAt reads n bytes at a pointer without copying: the bytes live in this module's memory.
func bytesAt(ptr, n uint32) string {
	if n == 0 {
		return ""
	}
	return unsafe.String((*byte)(unsafe.Pointer(uintptr(ptr))), int(n))
}

%SUPPORT%
`

// supportFor writes the typed wrappers for the exports whose shape is known.
func supportFor(exports []Export) string {
	var b strings.Builder
	for _, e := range exports {
		name := exportName(e.Name)
		switch {
		case len(e.Params) == 1 && e.Params[0] == "string" && isNumber(e.Returns):
			fmt.Fprintf(&b, `// Wasm%sStringNumber answers %s(string) with a number.
func Wasm%sStringNumber(ptr, n uint32) float64 {
	%s
}

`, name, e.Name, name, typedCall(e.Name, "bytesAt(ptr, n)", "stringNumber", "string"))
		case len(e.Params) == 1 && e.Params[0] == "string" && isText(e.Returns):
			fmt.Fprintf(&b, `// Wasm%sStringText answers %s(string) with a string, quoted into out.
func Wasm%sStringText(ptr, n uint32, out []byte) uint32 {
	v, err := portCall(%q, []any{bytesAt(ptr, n)})
	if err != nil {
		q := strconv.AppendQuote(out[:0], err.Error())
		return uint32(len(q))
	}
	text, ok := v.(string)
	if !ok {
		return 0
	}
	q := strconv.AppendQuote(out[:0], text)
	return uint32(len(q))
}

`, name, e.Name, name, e.Name)
		case len(e.Params) == 2 && e.Params[0] == "number" && e.Params[1] == "number" &&
			isNumber(e.Returns):
			fmt.Fprintf(&b, `// Wasm%sNumberNumber answers %s(number, number) with a number.
func Wasm%sNumberNumber(a, b float64) float64 {
	%s
}

`, name, e.Name, name, typedCall(e.Name, "a, b", "numberNumber", "number"))
		}
	}
	return b.String()
}

// Run writes the module and the wrapper, and builds the wasm.
func Run(opts Options) ([]string, error) {
	dir, err := filepath.Abs(opts.CrateDir)
	if err != nil {
		return nil, err
	}
	wasmDir := filepath.Join(dir, "cmd", "portwasm")
	if err := os.MkdirAll(wasmDir, 0o755); err != nil {
		return nil, err
	}
	detectPortStyle(dir)
	src := strings.ReplaceAll(module, cratePlaceholder, opts.Crate)

	support := filepath.Join(dir, "wasm_support.go")
	body := supportFor(opts.Typed)
	strconvImport := ""
	if strings.Contains(body, "strconv.") {
		strconvImport = "\t\"strconv\"\n"
	}
	mathImport := ""
	if strings.Contains(body, "math.") {
		mathImport = "\t\"math\"\n"
	}
	supportSrc := strings.ReplaceAll(crateSupport, "%MATH%", mathImport)
	supportSrc = strings.ReplaceAll(supportSrc, "%STRCONV%", strconvImport)
	supportSrc = strings.ReplaceAll(supportSrc, "%SUPPORT%", body)
	if err := os.WriteFile(support, []byte(supportSrc), 0o644); err != nil {
		return nil, err
	}
	direct := directEntries(opts.Typed)
	wasmSrc := strings.ReplaceAll(src, "%DIRECT%", direct)
	if err := os.WriteFile(filepath.Join(wasmDir, "main.go"), []byte(wasmSrc), 0o644); err != nil {
		return nil, err
	}
	quoted := make([]string, len(opts.Exports))
	for i, name := range opts.Exports {
		quoted[i] = fmt.Sprintf("%q", name)
	}
	js := strings.ReplaceAll(wrapper, "%EXPORTS%", "["+strings.Join(quoted, ", ")+"]")
	js = strings.ReplaceAll(js, "%JSWIRE_DECODE%", jswire.Decode)
	js = strings.ReplaceAll(js, "%JSWIRE_ENCODE%", jswire.Encode)
	js = strings.ReplaceAll(js, "REPLACE_OFFSET", fmt.Sprint(ReplyOffset))
	js = strings.ReplaceAll(js, "%DIRECT_MAP%", directMap(opts.Typed))
	js = strings.ReplaceAll(js, "%REPLY_OFFSET%", fmt.Sprint(ReplyOffset))
	wrapperPath := filepath.Join(dir, "index.wasm.mjs")
	if err := os.WriteFile(wrapperPath, []byte(js), 0o644); err != nil {
		return nil, err
	}

	out := filepath.Join(dir, "port.wasm")
	build := exec.Command(toolchain.Go(), "build", "-buildmode=c-shared", "-o", out, "./cmd/portwasm")
	build.Dir = dir
	build.Env = append(os.Environ(), "GOOS=wasip1", "GOARCH=wasm", "CGO_ENABLED=0")
	build.Stderr = os.Stderr
	if err := build.Run(); err != nil {
		return nil, fmt.Errorf("building the wasm module: %w", err)
	}
	return []string{support, filepath.Join(wasmDir, "main.go"), wrapperPath, out}, nil
}

// directEntries writes one exported function per shape the port has. A string argument and a number
// reply is the shape most ports have, and it is the one worth generating: no registry lookup, no
// []any boxing for the reply, no Marshal — the number comes back in a register.
func directEntries(exports []Export) string {
	var b strings.Builder
	for _, e := range exports {
		name := exportName(e.Name)
		switch {
		case len(e.Params) == 1 && e.Params[0] == "string" && isNumber(e.Returns):
			fmt.Fprintf(&b, `//go:wasmexport go_%s
//
// %s(string) -> number, direct: no registry lookup, no boxing of the reply.
func go%s(ptr uint32, n uint32) float64 {
	return port.Wasm%sStringNumber(ptr, n)
}

`, name, e.Name, name, name)
		case len(e.Params) == 1 && e.Params[0] == "string" && isText(e.Returns):
			fmt.Fprintf(&b, `//go:wasmexport go_%s_text
//
// %s(string) -> string, direct: the reply is written at replyOffset and its length returned.
func go%sText(ptr uint32, n uint32) uint32 {
	return port.Wasm%sStringText(ptr, n, scratch[replyOffset:])
}

`, name, e.Name, name, name)
		case len(e.Params) == 2 && e.Params[0] == "number" && e.Params[1] == "number" &&
			isNumber(e.Returns):
			fmt.Fprintf(&b, `//go:wasmexport go_%s_num
//
// %s(number, number) -> number, direct.
func go%sNum(a float64, b float64) float64 {
	return port.Wasm%sNumberNumber(a, b)
}

`, name, e.Name, name, name)
		}
	}
	return b.String()
}

// exportName turns an export name into a Go identifier suffix.
func exportName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if r >= 'a' && r <= 'z' {
			if b.Len() == 0 {
				b.WriteRune(unicode.ToUpper(r))
				continue
			}
			b.WriteRune(r)
			continue
		}
		if (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "Call"
	}
	return b.String()
}

func isNumber(t string) bool { return t == "number" }
func isText(t string) bool   { return t == "string" }

// directMap writes the wrapper's table of direct entries: what each one takes and how to read its reply.
func directMap(exports []Export) string {
	var b strings.Builder
	b.WriteString("{\n")
	for _, e := range exports {
		name := exportName(e.Name)
		switch {
		case len(e.Params) == 1 && e.Params[0] == "string" && isNumber(e.Returns):
			fmt.Fprintf(&b, `  %q: arg => {
    const area = argView()
    const written = encoder.encodeInto(arg, area)
    if (written.read !== arg.length) return decode(raw(%q, JSON.stringify([arg])))
    const v = exports.go_%s(scratch, written.written)
    if (Number.isNaN(v)) { const r = raw(%q, JSON.stringify([arg])); return decode(r) }
    return v
  },
`, e.Name, e.Name, name, e.Name)
		case len(e.Params) == 2 && e.Params[0] == "number" && e.Params[1] == "number" &&
			isNumber(e.Returns):
			fmt.Fprintf(&b, `  %q: (a, b) => {
    const v = exports.go_%s_num(a, b)
    if (Number.isNaN(v)) return decode(raw(%q, JSON.stringify([a, b])))
    return v
  },
`, e.Name, name, e.Name)
		case len(e.Params) == 1 && e.Params[0] == "string" && isText(e.Returns):
			fmt.Fprintf(&b, `  %q: arg => {
    const area = argView()
    const written = encoder.encodeInto(arg, area)
    if (written.read !== arg.length) return decode(raw(%q, JSON.stringify([arg])))
    const len = exports.go_%s_text(scratch, written.written)
    if (len === 0) return decode(raw(%q, JSON.stringify([arg])))
    return JSON.parse(decoder.decode(view().subarray(scratch + REPLACE_OFFSET, scratch + REPLACE_OFFSET + len)))
  },
`, e.Name, e.Name, name, e.Name)
		}
	}
	b.WriteString("}")
	return b.String()
}

// portStyle says whether the crate's port declares a typed function for an export, which is what the
// fast path calls, or only the registry entry every scaffold produces. It was declared and never filled
// for a while: every wrapper went through the registry, and the typed path that measured 53 ns a call was
// dead code, which is why the wasm bridge measured 0.23 µs instead of 0.05.
var portStyle = map[string]bool{}

// detectPortStyle reads port.go and records which exports are declared with a typed signature. A port
// written by hand as `func f(a, b float64) float64` gets the direct call; the scaffold's `func f(args
// []any)` does not.
func detectPortStyle(dir string) {
	portStyle = map[string]bool{}
	file, err := gofile(dir, "port.go")
	if err != nil {
		return
	}
	fset := token.NewFileSet()
	parsed, err := goparser.ParseFile(fset, file, nil, 0)
	if err != nil {
		return
	}
	for _, decl := range parsed.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || !fn.Name.IsExported() {
			continue
		}
		// The port's own name is lower case (rangeOf) and the typed wrapper is exported (RangeOf); the
		// generated wrapper calls the lower-case one, so record both spellings.
		if len(fn.Name.Name) > 0 {
			lower := strings.ToLower(fn.Name.Name[:1]) + fn.Name.Name[1:]
			portStyle[lower] = true
		}
		// The scaffold's shape is one parameter of type []any: anything else is a typed function.
		if fn.Type.Params != nil && len(fn.Type.Params.List) == 1 {
			if arr, ok := fn.Type.Params.List[0].Type.(*ast.ArrayType); ok && arr.Len == nil {
				if id, ok := arr.Elt.(*ast.Ident); ok && id.Name == "any" {
					continue
				}
			}
		}
		portStyle[fn.Name.Name] = true
	}
}

// gofile answers the path of a file in the crate's port package.
func gofile(dir, name string) (string, error) {
	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err != nil {
		return "", err
	}
	return path, nil
}

// typedCall writes the body of a wrapper: a direct call when the port declares that function, and the
// registry otherwise. The registry always exists, so the generated file compiles for every crate; a
// crate that types its port gets the version that measured 53 ns a call.
func typedCall(export, args, shape, first string) string {
	if portStyle[export] {
		return fmt.Sprintf("v, err := %s(%s)\n\tif err != nil {\n\t\treturn math.NaN()\n\t}\n\treturn v", export, args)
	}
	return fmt.Sprintf("v, err := portCall(%q, []any{%s})\n\tif err != nil {\n\t\treturn math.NaN()\n\t}\n\tf, ok := v.(float64)\n"+
		"\tif !ok {\n\t\treturn math.NaN()\n\t}\n\treturn f", export, args)
}
