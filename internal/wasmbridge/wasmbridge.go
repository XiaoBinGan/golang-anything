// Package wasmbridge builds the in-process path that actually wins: a Go module compiled to
// WebAssembly with a reactor entry point, called from JavaScript as an ordinary function.
//
// It exists because two other designs were measured and rejected: cgo plus N-API costs 215 ns a call
// (the cgo ABI is 40–60 ns of it before any work), and a shared-memory ring costs 182 ns even between
// two JavaScript threads. A wasm call is neither: it is a function call into the same address space,
// 18 ns for a leaf port and about 120 ns for one that allocates.
//
// The one thing that matters and cost a day to find: `-buildmode=c-shared`. Without it, a wasip1 module
// is a command — it initialises in `_start` and every export aborts with "notInitialized". With it, the
// module is a reactor, real Go runs inside the exports, and `//go:wasmexport` is the whole interface.
package wasmbridge

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Scratch is the layout both sides agree on: the caller writes the name and arguments at the base,
// the module writes the reply 64 KiB further in, and nothing else is shared.
const (
	ScratchSize = 128 << 10
	ReplyOffset = 64 << 10
)

// Options is one wasm build.
type Options struct {
	CrateDir string
	Crate    string
	Exports  []string
	// LeaveTinyGo is for the day the toolchain here has no wasm target: it writes the sources and says
	// what to run, instead of failing halfway.
	LeaveTinyGo bool
}

// module is the Go side: two exports, one scratch buffer, and the same Answer the other bridges use.
const module = `// Command portwasm is the in-process port as a WebAssembly reactor.
//
//	GOOS=wasip1 GOARCH=wasm go build -buildmode=c-shared -o port.wasm ./cmd/portwasm
//
// The caller writes the export name and its JSON arguments into the scratch buffer, calls go_call, and
// reads the reply from the second half of the same buffer. No pipe, no cgo, no N-API — the call crosses
// nothing at all.
package main

import (
	"encoding/json"
	"unsafe"

	port "` + cratePlaceholder + `"
)

const (
	scratchSize = 128 << 10
	replyOffset = 64 << 10
)

// scratch is the shared buffer: [0, 64 KiB) for the request, [64 KiB, 128 KiB) for the reply.
var scratch [scratchSize]byte

//go:wasmexport go_scratch
func goScratch() uint32 {
	return uint32(uintptr(unsafe.Pointer(&scratch[0])))
}

//go:wasmexport go_call
//
// Answers one call: the reply is written at ReplyOffset and its length is returned, or 0 when the
// request does not fit or the port failed in a way it cannot report.
func goCall(nameLen uint32, argsLen uint32) uint32 {
	name := byteString(&scratch[0], nameLen)
	args := byteString(&scratch[nameLen], argsLen)
	reply := port.AnswerJSON(name, args)
	if uint32(len(reply)) > uint32(len(scratch)-replyOffset) {
		return 0
	}
	copy(scratch[replyOffset:], reply)
	return uint32(len(reply))
}

//go:wasmexport go_call1
//
// The one-string call: the argument is the string itself, not JSON, and the reply is the value's JSON
// only (no {"ok":…} envelope). Most ports are this shape, and skipping the encode is most of the win.
func goCall1(nameLen uint32, argLen uint32) uint32 {
	name := byteString(&scratch[0], nameLen)
	arg := byteString(&scratch[nameLen], argLen)
	fn, ok := port.Registry[name]
	if !ok {
		return 0
	}
	v, err := fn([]any{arg})
	var reply []byte
	if err != nil {
		reply, _ = json.Marshal(err.Error())
	} else {
		b, err := json.Marshal(v)
		if err != nil {
			return 0
		}
		reply = b
	}
	if uint32(len(reply)) > uint32(len(scratch)-replyOffset) {
		return 0
	}
	copy(scratch[replyOffset:], reply)
	return uint32(len(reply))
}

// byteString reads n bytes as a string without copying: the bytes live in this module's memory and the
// port only reads them.
func byteString(p *byte, n uint32) string {
	if n == 0 {
		return ""
	}
	return unsafe.String(p, int(n))
}

func main() {}
`

// wrapper is the JavaScript side: one wasm instance, one scratch buffer, one call per invocation.
const wrapper = `// Generated by go-anything: the port as WebAssembly, called in-process.
//
//   import port from './index.wasm.mjs'
//   port.count('a b  ')          // 2
//   port.raw('count', '["a b  "]')  // the JSON reply, for the cases the typed path cannot carry
//
// There is no child process and no addon: the module is a reactor, initialised once, and a call is a
// function call into the same address space.
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { WASI } from 'node:wasi'

const here = new URL('.', import.meta.url)
const bytes = await readFile(new URL('port.wasm', here))

// A reactor needs no argv or environment, and it must not be started: ` + "`initialize`" + ` runs the
// module's init without running main to completion.
const wasi = new WASI({ version: 'preview1', args: [], env: {} })
const { instance } = await WebAssembly.instantiate(bytes, wasi.getImportObject())
try {
  wasi.initialize(instance)
} catch (e) {
  if (!String(e.message).includes('already initialized')) throw e
}

const exports = instance.exports

// The Go runtime grows its memory, and growing detaches the old view: keep the view and refresh it
// when the buffer it points at is gone.
let memory = new Uint8Array(exports.memory.buffer)
function view() {
  if (memory.buffer.byteLength === 0) memory = new Uint8Array(exports.memory.buffer)
  return memory
}
const scratch = exports.go_scratch()
const encoder = new TextEncoder()
const decoder = new TextDecoder()

// decode turns the wire markers back into JavaScript values.
const decode = v => {
  if (Array.isArray(v)) return v.map(decode)
  if (v && typeof v === 'object') {
    const keys = Object.keys(v)
    if (keys.length === 1) {
      if (typeof v.$number === 'string') {
        return v.$number === 'NaN' ? NaN : v.$number === 'Infinity' ? Infinity
          : v.$number === '-Infinity' ? -Infinity : -0
      }
      if (typeof v.$bigint === 'string') return BigInt(v.$bigint)
      if (Array.isArray(v.$utf16)) return String.fromCharCode(...v.$utf16)
      if (v.$undefined === true) return undefined
    }
    const out = {}
    for (const k of keys) out[k] = decode(v[k])
    return out
  }
  return v
}

// raw answers one call with the export name and an arguments array already encoded as JSON.
function raw(name, argsJSON) {
  const nameBytes = encoder.encode(name)
  const argBytes = encoder.encode(argsJSON)
  if (nameBytes.length + argBytes.length >= %REPLY_OFFSET%) {
    throw new Error('go-anything: request larger than the scratch buffer')
  }
  const mem = view()
  mem.set(nameBytes, scratch)
  mem.set(argBytes, scratch + nameBytes.length)
  const len = exports.go_call(nameBytes.length, argBytes.length)
  if (len === 0) throw new Error('go-anything: ' + name + ' failed')
  const text = decoder.decode(view().subarray(scratch + %REPLY_OFFSET%, scratch + %REPLY_OFFSET% + len))
  const reply = JSON.parse(text)
  if (reply.error) throw new Error(reply.error)
  if (reply.panic) throw new Error('Go panic: ' + reply.panic)
  return reply.ok
}

// A call with one string argument takes the fast path: the name's bytes are encoded once at load, the
// argument is written straight into the module's memory, and the reply is the value's JSON.
const names = new Map(%EXPORTS%.map(name => [name, encoder.encode(name)]))
const call1 = exports.go_call1
// One reusable view over the argument area, refreshed when the runtime grows its memory.
let argArea = null
function argView() {
  const mem = view()
  if (argArea === null || argArea.buffer !== mem.buffer) {
    argArea = mem.subarray(scratch, scratch + (%REPLY_OFFSET% - 1024))
  }
  return argArea
}

function fast(name, arg) {
  const nameBytes = names.get(name)
  const area = argView()
  // Write the name into the same area, then the argument right after it: one encoding, one call.
  area.set(nameBytes, 0)
  const written = encoder.encodeInto(arg, area.subarray(nameBytes.length))
  if (written.read !== arg.length) return raw(name, JSON.stringify([arg]))
  const len = call1(nameBytes.length, written.written)
  if (len === 0) throw new Error('go-anything: ' + name + ' failed')
  return JSON.parse(decoder.decode(view().subarray(scratch + %REPLY_OFFSET%, scratch + %REPLY_OFFSET% + len)))
}

const port = { raw }
for (const name of %EXPORTS%) {
  port[name] = (...args) => {
    if (args.length === 1 && typeof args[0] === 'string' && call1) {
      try {
        return decode(fast(name, args[0]))
      } catch (e) {
        return decode(raw(name, JSON.stringify(args))) // fall back for a payload the fast path cannot hold
      }
    }
    return decode(raw(name, JSON.stringify(args)))
  }
}
export default port
`

const cratePlaceholder = "__CRATE__"

// Run writes the module and the wrapper, and builds the wasm.
func Run(opts Options) ([]string, error) {
	dir, err := filepath.Abs(opts.CrateDir)
	if err != nil {
		return nil, err
	}
	wasmDir := filepath.Join(dir, "cmd", "portwasm")
	if err := os.MkdirAll(wasmDir, 0o755); err != nil {
		return nil, err
	}
	src := strings.ReplaceAll(module, cratePlaceholder, opts.Crate)
	if err := os.WriteFile(filepath.Join(wasmDir, "main.go"), []byte(src), 0o644); err != nil {
		return nil, err
	}

	quoted := make([]string, len(opts.Exports))
	for i, name := range opts.Exports {
		quoted[i] = fmt.Sprintf("%q", name)
	}
	js := strings.ReplaceAll(wrapper, "%EXPORTS%", "["+strings.Join(quoted, ", ")+"]")
	js = strings.ReplaceAll(js, "%REPLY_OFFSET%", fmt.Sprint(ReplyOffset))
	wrapperPath := filepath.Join(dir, "index.wasm.mjs")
	if err := os.WriteFile(wrapperPath, []byte(js), 0o644); err != nil {
		return nil, err
	}

	out := filepath.Join(dir, "port.wasm")
	build := exec.Command("go", "build", "-buildmode=c-shared", "-o", out, "./cmd/portwasm")
	build.Dir = dir
	build.Env = append(os.Environ(), "GOOS=wasip1", "GOARCH=wasm", "CGO_ENABLED=0")
	build.Stderr = os.Stderr
	if err := build.Run(); err != nil {
		return nil, fmt.Errorf("building the wasm module: %w", err)
	}
	return []string{filepath.Join(wasmDir, "main.go"), wrapperPath, out}, nil
}
