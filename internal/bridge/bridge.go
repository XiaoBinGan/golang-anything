// Package bridge generates the front door: a long-lived Go process that answers calls over stdio, and
// thin wrappers that let the original's callers keep calling the same names.
//
// This is where a Go port differs from a Rust one. rust-anything hands out napi-rs, PyO3, JNI or FFI
// modules; Go has no such thing for a plugin boundary, and a c-shared library plus cgo per host is a
// week of work per language. A stdio protocol costs about 20–40 µs per call and works in every
// runtime that can spawn a process — so the honest first bridge is this one, and a c-shared fast path
// can come later for the functions that need it.
package bridge

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/xiaobingan/go-anything/internal/jswire"
)

// Options is one bridge generation.
type Options struct {
	CrateDir string
	Crate    string
	Unit     string
	Exports  []string
}

// Run writes cmd/portctl/main.go plus the host wrappers, and returns the files it wrote.
func Run(opts Options) ([]string, error) {
	dir := filepath.Join(opts.CrateDir, "cmd", "portctl")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	ctl := `// Command portctl answers calls to the port over stdio: one JSON object per line in, one out.
//
// The protocol is deliberately dull, because every runtime can speak it:
//
//	in:  {"name":"count","args":["a b "]}
//	out: {"ok":2} | {"error":"RangeError: …"} | {"panic":"…"}
//
// It is long-lived: a host starts it once and keeps the pipe open, so the cost is the pipe, not a
// process per call.
package main

import (
	"bufio"
	"encoding/json"
	"os"

	port "` + opts.Crate + `"
)

type request struct {
	Name string ` + "`json:\"name\"`" + `
	Args []any  ` + "`json:\"args\"`" + `
}

type reply struct {
	Ok    any    ` + "`json:\"ok,omitempty\"`" + `
	Error string ` + "`json:\"error,omitempty\"`" + `
	Panic string ` + "`json:\"panic,omitempty\"`" + `
}

func main() {
	in := bufio.NewScanner(os.Stdin)
	in.Buffer(make([]byte, 1<<20), 1<<20)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()
	enc := json.NewEncoder(out)
	for in.Scan() {
		line := in.Bytes()
		if len(line) == 0 {
			continue
		}
		var req request
		if err := json.Unmarshal(line, &req); err != nil {
			enc.Encode(reply{Error: "bad request: " + err.Error()})
			out.Flush()
			continue
		}
		enc.Encode(port.Answer(req.Name, req.Args))
		out.Flush()
	}
}

`
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(ctl), 0o644); err != nil {
		return nil, err
	}

	answer := `// Generated by go-anything: one call in, one answer out, for the stdio bridge.
package port

import (
	"encoding/json"
	"fmt"
	"math"
)

// Call answers one call with arguments as a CLI has them: strings. It turns the reply into the text a
// command prints, and an error into the error the front door reports.
func Call(name string, args []any) (string, error) {
	v, err := invoke(name, args)
	if err != nil {
		return "", err
	}
	b, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	return string(b), nil
}

// invoke is the one place a call happens: the in-process bridge and the CLI both go through it, so
// neither allocates the reply object the other builds anyway.
func invoke(name string, args []any) (any, error) {
	fn, ok := Registry[name]
	if !ok {
		return nil, fmt.Errorf("not ported: %s", name)
	}
	defer func() {
		_ = recover()
	}()
	return safeCall(fn, DecodeArgs(args))
}

// AnswerJSON parses the arguments as JSON and marshals the reply: the one shape every bridge can
// carry, including the WebAssembly one where there is no C string to hand back.
func AnswerJSON(name string, argsJSON string) []byte {
	var args []any
	if argsJSON != "" && argsJSON != "null" {
		if err := json.Unmarshal([]byte(argsJSON), &args); err != nil {
			return []byte("{\"error\":\"bad args\"}")
		}
	}
	reply := Answer(name, args)
	b, err := json.Marshal(reply)
	if err != nil {
		return []byte("{\"error\":\"reply\"}")
	}
	return b
}

// Answer runs one call and never lets a panic out: the host sees a reply, not a dead process.
func Answer(name string, args []any) map[string]any {
	v, err := invoke(name, args)
	if err != nil {
		return map[string]any{"error": err.Error()}
	}
	return map[string]any{"ok": mark(v)}
}

// Undefined is JavaScript's undefined: a port returns this where the original answered undefined, and
// the wire spells it as a marker. Returning nil would say null, which is a different value.
type Undefined struct{}

// mark writes NaN, ±Infinity, -0, undefined and code units the way the original's codec does, so a host
// sees values rather than spellings JSON cannot carry.
func mark(v any) any {
	switch x := v.(type) {
	case Undefined:
		return map[string]any{"$undefined": true}
	case float64:
		switch {
		case math.IsNaN(x):
			return map[string]any{"$number": "NaN"}
		case math.IsInf(x, 1):
			return map[string]any{"$number": "Infinity"}
		case math.IsInf(x, -1):
			return map[string]any{"$number": "-Infinity"}
		case x == 0 && math.Signbit(x):
			return map[string]any{"$number": "-0"}
		}
		return x
	case []uint16:
		out := make([]any, len(x))
		for i, u := range x {
			out[i] = float64(u)
		}
		return map[string]any{"$utf16": out}
	case []any:
		out := make([]any, len(x))
		for i, item := range x {
			out[i] = mark(item)
		}
		return out
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, item := range x {
			out[k] = mark(item)
		}
		return out
	}
	return v
}

// safeCall turns a panic into an error a host can raise.
func safeCall(fn Fn, args []any) (v any, err error) {
	defer func() {
		if r := recover(); r != nil {
			v, err = nil, fmt.Errorf("panic: %v", r)
		}
	}()
	return fn(args)
}
`
	if err := os.WriteFile(filepath.Join(opts.CrateDir, "answer.go"), []byte(answer), 0o644); err != nil {
		return nil, err
	}

	js := `// Generated by go-anything: the same functions, answered by the Go port over a pipe.
//
//   const port = require('./index.cjs')
//   await port.count('a b ')      // 2
//   await port.count('a b ', {raw: true}) // {ok: 2}
//
// The child process starts on the first call and stays up. Calls are queued: one request, one reply.
const { spawn } = require('node:child_process')
const path = require('node:path')

// The in-process addon comes first: a call through it costs a function call, not a pipe round trip.
// GO_ANYTHING_NO_ADDON=1 forces the pipe, so a test can check the fallback path on a machine where the
// addon is built — otherwise the addon is the only path anything ever runs.
let addon = null
if (process.env.GO_ANYTHING_NO_ADDON !== '1') {
  try {
    // A module-relative require resolves against this file's folder, whatever the caller's cwd is.
    addon = require('./addon.node')
  } catch {}
}

const bin = process.env.GO_ANYTHING_PORTCTL || path.join(__dirname, 'portctl')

// Without either the addon or the binary there is nothing to answer with, and spawning a missing file
// raises an unhandled 'error' event instead of a sentence a person can act on.
const { existsSync } = require('node:fs')
if (!addon && !existsSync(bin)) {
  throw new Error(
    'go-anything: no bridge in ' + __dirname + '. Build one: ' +
    'go-anything build --fast <crate> for the in-process addon (fastest), or ' +
    'go-anything build <crate> for the stdio binary.'
  )
}
let child = null
let queue = []
let buffer = ''

function start() {
  if (child) return child
  child = spawn(bin, [], { stdio: ['pipe', 'pipe', 'inherit'] })
  child.stdout.setEncoding('utf8')
  child.stdout.on('data', chunk => {
    buffer += chunk
    let i
    while ((i = buffer.indexOf('\n')) >= 0) {
      const line = buffer.slice(0, i)
      buffer = buffer.slice(i + 1)
      if (!line.trim()) continue
      const next = queue.shift()
      if (next) next(line)
    }
  })
  child.on('exit', code => {
    const waiting = queue
    queue = []
    child = null
    for (const fail of waiting) fail(` + "`portctl exited with ${code}`" + `)
  })
  return child
}

%JSWIRE_ENCODE%

%JSWIRE_DECODE%

function ask(name, args) {
  if (addon) {
    const reply = JSON.parse(addon.answer(name, JSON.stringify(encode(args ?? []))))
    if (reply.error) return Promise.reject(new Error(reply.error))
    if (reply.panic) return Promise.reject(new Error('Rust panic: ' + reply.panic))
    return Promise.resolve(decode(reply.ok))
  }
  const proc = start()
  return new Promise((resolve, reject) => {
    queue.push(line => {
      let reply
      try {
        reply = JSON.parse(line)
      } catch (e) {
        return reject(new Error('portctl said: ' + line))
      }
      if (reply.error) return reject(new Error(reply.error))
      if (reply.panic) return reject(new Error('Rust panic: ' + reply.panic))
      resolve(decode(reply.ok))
    })
    proc.stdin.write(JSON.stringify({ name, args: encode(args) }) + '\n')
  })
}

const functions = [%s]

const port = {}
for (const name of functions) {
  // In-process the call is synchronous, and that is the point of building the addon: a package whose
  // functions all return promises cannot stand in for a synchronous original. The promise form stays
  // for the pipe, where a call has to wait for an answer.
  port[name] = addon
    ? (...args) => {
        try {
          return port.callSync(name, ...args)
        } catch (e) {
          // A port that throws must throw the original's error, not a rejected promise.
          throw e
        }
      }
    : async (...args) => ask(name, args)
}
port.async = {}
for (const name of functions) {
  port.async[name] = async (...args) => ask(name, args)
}
// callSync is possible only in-process: it throws where a pipe would have to wait.
port.callSync = (name, ...args) => {
  if (!addon) throw new Error('callSync needs the in-process addon: run go-anything build --fast')
  // One string argument is the shape most ports have: the addon answers it without JSON on either side.
  if (addon.answer1 && args.length === 1 && typeof args[0] === 'string') {
    const text = addon.answer1(name, args[0])
    if (text === null) throw new Error('go-anything: ' + name + ' failed')
    return decode(JSON.parse(text))
  }
  const reply = JSON.parse(addon.answer(name, JSON.stringify(encode(args))))
  if (reply.error) throw new Error(reply.error)
  if (reply.panic) throw new Error('Rust panic: ' + reply.panic)
  return decode(reply.ok)
}
// callMany answers N calls of the same export in one crossing: the fixed cost of leaving the runtime
// is paid once, so the per-call cost inside a batch is a fraction of a single call's.
port.callMany = (name, list) => {
  if (!addon || !addon.answerBatch) {
    throw new Error('callMany needs the in-process addon: run go-anything build --fast')
  }
  const out = addon.answerBatch(list.map(() => name), list)
  if (out === null) throw new Error('go-anything: batch failed')
  return out.map(text => decode(JSON.parse(text)))
}
// callNumbers answers a batch of one-string calls that return a number, through typed buffers: the
// arguments go in as one UTF-8 blob plus a length table, the answers come back as a Float64Array.
// Nothing is marshalled and no string is created per call, which is what a tight loop needs.
port.callNumbers = (name, texts) => {
  if (!addon || !addon.numbers) {
    throw new Error('callNumbers needs the in-process addon: run go-anything build --fast')
  }
  const encoder = new TextEncoder()
  const blobs = texts.map(t => encoder.encode(t))
  let total = 0
  for (const b of blobs) total += b.length
  const blob = new Uint8Array(total)
  const lens = new Uint32Array(texts.length)
  let at = 0
  blobs.forEach((b, i) => {
    blob.set(b, at)
    at += b.length
    lens[i] = b.length
  })
  const out = addon.numbers(name, blob, lens)
  if (out === null) throw new Error('go-anything: ' + name + ' failed on a batch')
  return out // Float64Array; NaN marks a call that raised
}
port.inProcess = !!addon
port.call = ask
port.close = () => {
  if (child) child.kill()
  child = null
}
module.exports = port
`
	// Fill the wire helpers before the format, not after: fmt would read "%JSWIRE" as a verb.
	js = strings.ReplaceAll(js, "%JSWIRE_DECODE%", jswire.Decode)
	js = strings.ReplaceAll(js, "%JSWIRE_ENCODE%", jswire.Encode)
	body := fmt.Sprintf(js, quoteList(opts.Exports))
	if err := os.WriteFile(filepath.Join(opts.CrateDir, "index.cjs"), []byte(body), 0o644); err != nil {
		return nil, err
	}

	py := `"""Generated by go-anything: the same functions, answered by the Go port over a pipe.

    import port
    port.count("a b ")      # 2

One child process, one call at a time behind a lock: answers cannot interleave.
"""
import json
import os
import subprocess
import threading

_BIN = os.environ.get("GO_ANYTHING_PORTCTL", os.path.join(os.path.dirname(__file__), "portctl"))
_proc = None
_lock = threading.Lock()


def _start():
    global _proc
    if _proc is None:
        _proc = subprocess.Popen(
            [_BIN], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1
        )
    return _proc


def _decode(v):
    """Markers back to Python: float('nan'), inf, -0.0, bytes for code units, None for undefined."""
    if isinstance(v, list):
        return [_decode(x) for x in v]
    if isinstance(v, dict):
        if len(v) == 1:
            if isinstance(v.get("$number"), str):
                return {"NaN": float("nan"), "Infinity": float("inf"),
                        "-Infinity": float("-inf"), "-0": -0.0}[v["$number"]]
            if isinstance(v.get("$bigint"), str):
                return int(v["$bigint"])
            if isinstance(v.get("$utf16"), list):
                return "".join(chr(u) for u in v["$utf16"])
            if v.get("$undefined") is True:
                return None
        return {k: _decode(x) for k, x in v.items()}
    return v


def call(name, *args):
    """Answer one call, or raise what the port raised."""
    with _lock:
        proc = _start()
        proc.stdin.write(json.dumps({"name": name, "args": list(args)}) + "\n")
        proc.stdin.flush()
        line = proc.stdout.readline()
    if not line:
        raise RuntimeError("portctl exited")
    reply = json.loads(line)
    if reply.get("error"):
        raise RuntimeError(reply["error"])
    if reply.get("panic"):
        raise RuntimeError("Rust panic: " + reply["panic"])
    return _decode(reply.get("ok"))


def close():
    global _proc
    if _proc is not None:
        _proc.stdin.close()
        _proc.wait()
        _proc = None


%s
`
	wrappers := make([]string, 0, len(opts.Exports))
	for _, name := range opts.Exports {
		wrappers = append(wrappers, fmt.Sprintf("def %s(*args):\n    return call(%q, *args)\n", name, name))
	}
	if err := os.WriteFile(filepath.Join(opts.CrateDir, "port.py"), []byte(fmt.Sprintf(py, joinWrappers(wrappers))), 0o644); err != nil {
		return nil, err
	}

	return []string{
		filepath.Join(dir, "main.go"),
		filepath.Join(opts.CrateDir, "answer.go"),
		filepath.Join(opts.CrateDir, "index.cjs"),
		filepath.Join(opts.CrateDir, "port.py"),
	}, nil
}

func quoteList(items []string) string {
	out := ""
	for i, s := range items {
		if i > 0 {
			out += ", "
		}
		out += fmt.Sprintf("%q", s)
	}
	return out
}

func joinWrappers(lines []string) string {
	out := ""
	for _, line := range lines {
		out += line + "\n"
	}
	return out
}
