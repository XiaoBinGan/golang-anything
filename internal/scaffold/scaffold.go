// Package scaffold writes the Go side of a port: a registry, stubs, and a driver that answers the
// recorded cases.
//
// This is where the design differs from rust-anything: there is no napi-rs, PyO3 or JNI for Go, so a
// Go port reaches other runtimes through cgo and `go build -buildmode=c-shared`. The prototype
// keeps to the JSON wire first (one exported C function that takes and returns a string), because a
// correct slow bridge proves the loop before a fast one exists.
package scaffold

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/XiaoBinGan/golang-anything/internal/analyze"
)

// Options is one scaffold run.
type Options struct {
	CrateDir string
	Unit     analyze.Unit
	Crate    string
	Force    bool
	// SkipPort leaves port.go alone: `refresh` regenerates the binding, never the work.
	SkipPort bool
}

// Run writes <crate>/port.go, <crate>/cmd/godriver/main.go and <crate>/golang-anything.json.
func Run(opts Options) ([]string, error) {
	if err := os.MkdirAll(filepath.Join(opts.CrateDir, "cmd", "godriver"), 0o755); err != nil {
		return nil, err
	}
	portPath := filepath.Join(opts.CrateDir, "port.go")
	if _, err := os.Stat(portPath); err == nil && !opts.Force && !opts.SkipPort {
		return nil, fmt.Errorf("%s exists: pass --force to overwrite the stubs", portPath)
	}
	writePort := !opts.SkipPort || !fileExists(portPath)
	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Package port is the Go port of %s, made by golang-anything.
//
// Fill in each function; %q keeps the answer the original gave, so a finished port returns it and
// nothing else. Regenerate the stubs with `+"`golang-anything scaffold --force`"+`.
package port

import "fmt"

// Fn is one callable unit function: arguments in, answer out.
type Fn func(args []any) (any, error)

// Registry is what the driver dispatches on. The name is the original's export name.
var Registry = map[string]Fn{
`, opts.Unit.ID, "cases.jsonl")
	for _, e := range opts.Unit.Exports {
		fmt.Fprintf(&buf, "\t%q: %s,\n", e.Name, goName(e.Name))
	}
	buf.WriteString("}\n\n")
	for _, e := range opts.Unit.Exports {
		if e.Blocked != "" {
			fmt.Fprintf(&buf, `// %s stays in the original (%s): this stub is here so the registry names every export.
func %s(args []any) (any, error) {
	return nil, fmt.Errorf("stays in the original: %s")
}

`, goName(e.Name), e.Blocked, goName(e.Name), e.Blocked)
			continue
		}
		fmt.Fprintf(&buf, `// %s ports %s from %s (line %d, %d parameters).
// Signature: %s
func %s(args []any) (any, error) {
	return nil, fmt.Errorf("not implemented: port %s")
}

`, goName(e.Name), e.Name, opts.Unit.ID, e.Line, len(e.Params), signature(e), goName(e.Name), e.Name)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated port does not parse: %w", err)
	}
	if writePort {
		if err := os.WriteFile(portPath, formatted, 0o644); err != nil {
			return nil, err
		}
	}

	wire := `// Wire markers: JSON cannot carry NaN, ±Infinity, -0, undefined or a lone surrogate, so answers and
// arguments travel with a marker and are decoded here. Generated by golang-anything; keep it in step with
// the tool's own codec.
package port

import (
	"math"
	"unicode/utf16"
)

// UTF16 is a JavaScript string that has no valid UTF-8 form: a lone surrogate survives as code units.
type UTF16 []uint16

// DecodeArgs turns the markers in a recorded argument list back into values.
func DecodeArgs(args []any) []any {
	out := make([]any, len(args))
	for i, a := range args {
		out[i] = decode(a)
	}
	return out
}

func decode(v any) any {
	switch x := v.(type) {
	case []any:
		out := make([]any, len(x))
		for i, item := range x {
			out[i] = decode(item)
		}
		return out
	case map[string]any:
		if len(x) == 1 {
			if n, ok := x["$number"].(string); ok {
				switch n {
				case "NaN":
					return math.NaN()
				case "Infinity":
					return math.Inf(1)
				case "-Infinity":
					return math.Inf(-1)
				case "-0":
					return math.Copysign(0, -1)
				}
			}
			if big, ok := x["$bigint"].(string); ok {
				return big
			}
			if units, ok := x["$utf16"].([]any); ok {
				out := make(UTF16, 0, len(units))
				for _, u := range units {
					if f, ok := u.(float64); ok {
						out = append(out, uint16(f))
					}
				}
				return out
			}
			if _, ok := x["$undefined"]; ok {
				return nil
			}
			if sig, ok := x["$abortSignal"].(map[string]any); ok {
				// A platform object: the port only needs to know whether it was aborted, and why.
				aborted, _ := sig["aborted"].(bool)
				return AbortSignal{Aborted: aborted, Reason: sig["reason"]}
			}
		}
		out := make(map[string]any, len(x))
		for k, item := range x {
			out[k] = decode(item)
		}
		return out
	}
	return v
}

// AbortSignal is the part of a JavaScript AbortSignal a port can act on.
type AbortSignal struct {
	Aborted bool
	Reason  any
}

// Text turns either a string or code units into UTF-16 units, the way JavaScript indexes a string.
func Text(v any) ([]uint16, bool) {
	switch x := v.(type) {
	case string:
		return utf16.Encode([]rune(x)), true
	case UTF16:
		return []uint16(x), true
	}
	return nil, false
}
`
	if err := os.WriteFile(filepath.Join(opts.CrateDir, "wire.go"), []byte(wire), 0o644); err != nil {
		return nil, err
	}

	driver := `// Command godriver answers a cases.jsonl from the port, so diff can compare the two sides.
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"math"
	"os"
	"strings"

	"` + opts.Crate + `"
)

type testCase struct {
	Fn     string         ` + "`json:\"fn\"`" + `
	Args   []any          ` + "`json:\"args\"`" + `
	Kwargs map[string]any ` + "`json:\"kwargs,omitempty\"`" + `
}

type answer struct {
	Fn    string ` + "`json:\"fn\"`" + `
	Args  []any  ` + "`json:\"args,omitempty\"`" + `
	Ok    any    ` + "`json:\"ok,omitempty\"`" + `
	Error string ` + "`json:\"error,omitempty\"`" + `
	Panic string ` + "`json:\"panic,omitempty\"`" + `
}

func main() {
	in, err := os.Open(os.Args[1])
	if err != nil {
		fail(err)
	}
	defer in.Close()
	out, err := os.Create(os.Args[2])
	if err != nil {
		fail(err)
	}
	defer out.Close()
	scan := bufio.NewScanner(in)
	scan.Buffer(make([]byte, 1<<20), 1<<20)
	w := bufio.NewWriter(out)
	defer w.Flush()
	enc := json.NewEncoder(w)
	for scan.Scan() {
		// A blank line is not a case: a recording of nothing leaves one, and failing on it turned an
		// empty crate into "unexpected end of JSON input".
		if len(strings.TrimSpace(scan.Text())) == 0 {
			continue
		}
		var c testCase
		if err := json.Unmarshal(scan.Bytes(), &c); err != nil {
			fail(err)
		}
		enc.Encode(answerOne(c))
	}
	if err := scan.Err(); err != nil {
		fail(err)
	}
}

// answerOne calls the port and turns a panic into an error, as the bridge must never crash the run.
func answerOne(c testCase) (a answer) {
	a.Fn = c.Fn
	// Echo the arguments: diff joins the two sides by the call, not by line number.
	a.Args = c.Args
	fn, ok := port.Registry[c.Fn]
	if !ok {
		a.Error = "not ported: " + c.Fn
		return a
	}
	defer func() {
		if r := recover(); r != nil {
			a.Ok = nil
			a.Error = ""
			a.Panic = fmt.Sprint(r)
		}
	}()
	v, err := fn(port.DecodeArgs(c.Args))
	if err != nil {
		a.Error = err.Error()
		return a
	}
	a.Ok = mark(v)
	return a
}

// mark writes NaN, ±Infinity, -0 and ints too large for JSON the way the original's codec does, so
// diff compares values rather than spellings.
func mark(v any) any {
	switch x := v.(type) {
	case port.Undefined:
		// The crate's Undefined: JavaScript's undefined, which nil would read as null.
		return map[string]any{"$undefined": true}
	case float64:
		switch {
		case math.IsNaN(x):
			return map[string]any{"$number": "NaN"}
		case math.IsInf(x, 1):
			return map[string]any{"$number": "Infinity"}
		case math.IsInf(x, -1):
			return map[string]any{"$number": "-Infinity"}
		case x == 0 && math.Signbit(x):
			return map[string]any{"$number": "-0"}
		}
		return x
	case []uint16:
		// Code units: the only way a lone surrogate survives the JSON boundary.
		out := make([]any, len(x))
		for i, u := range x {
			out[i] = float64(u)
		}
		return map[string]any{"$utf16": out}
	case []any:
		out := make([]any, len(x))
		for i, item := range x {
			out[i] = mark(item)
		}
		return out
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, item := range x {
			out[k] = mark(item)
		}
		return out
	}
	return v
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "godriver:", err)
	os.Exit(1)
}
`
	if err := os.WriteFile(filepath.Join(opts.CrateDir, "cmd", "godriver", "main.go"), []byte(driver), 0o644); err != nil {
		return nil, err
	}

	manifest := fmt.Sprintf(`{
  "schema": "golang-anything/port@1",
  "unit": %q,
  "crate": %q,
  "files": [%s],
  "exports": [%s],
  "wire": "json"
}
`, opts.Unit.ID, opts.Crate, quoteList(opts.Unit.Files), exportList(opts.Unit.Exports))
	manifestPath := filepath.Join(opts.CrateDir, "golang-anything.json")
	if err := os.WriteFile(manifestPath, []byte(manifest), 0o644); err != nil {
		return nil, err
	}
	files := []string{
		filepath.Join(opts.CrateDir, "wire.go"),
		filepath.Join(opts.CrateDir, "cmd", "godriver", "main.go"),
		manifestPath,
	}
	if writePort {
		files = append([]string{portPath}, files...)
	}
	return files, nil
}

// signature renders the original's TypeScript signature next to the stub, so filling it in does not
// mean opening the source again.
func signature(e analyze.Export) string {
	params := make([]string, len(e.Params))
	for i, p := range e.Params {
		params[i] = p.Name + ": " + p.Type
	}
	ret := e.Returns
	if ret == "" {
		ret = "any"
	}
	return fmt.Sprintf("%s(%s): %s", e.Name, strings.Join(params, ", "), ret)
}

func quoteList(items []string) string {
	parts := make([]string, len(items))
	for i, s := range items {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

// exportList is the manifest's export list: what the driver dispatches, the types the generator needs,
// the throw lines the gate insists on, and the reason an export stays in the original.
func exportList(exports []analyze.Export) string {
	parts := make([]string, len(exports))
	for i, e := range exports {
		types := make([]string, len(e.Params))
		for j, p := range e.Params {
			types[j] = fmt.Sprintf("%q", p.Type)
		}
		throws := make([]string, len(e.ThrowLines))
		for j, line := range e.ThrowLines {
			throws[j] = fmt.Sprint(line)
		}
		parts[i] = fmt.Sprintf(`{"name":%q,"params":[%s],"returns":%q,"line":%d,"throw_lines":[%s],"blocked":%q,"receiver":%q}`,
			e.Name, strings.Join(types, ","), e.Returns, e.Line, strings.Join(throws, ","), e.Blocked, e.Receiver)
	}
	return strings.Join(parts, ",")
}

// fileExists reports whether a path is an existing regular file.
func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// goName spells a unit's export as a Go identifier: `Get-Thing` cannot be a function name, and a name that
// starts with a digit cannot be one either. The original name stays the registry key and stays in the doc
// comment, so nothing is lost.
func goName(name string) string {
	// A name that is already a Go identifier stays as it is: `count` is called by that name from every
	// generated wrapper, and capitalising it produced `Count` in the stub and `count` at the call site.
	if isGoIdent(name) {
		return name
	}
	var b strings.Builder
	upper := true
	for _, r := range name {
		switch {
		case r == '-' || r == '.' || r == ' ' || r == ':' || r == '/':
			upper = true
		case (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_':
			if upper && r >= 'a' && r <= 'z' {
				b.WriteRune(r - 32)
			} else {
				b.WriteRune(r)
			}
			upper = false
		default:
			// Anything else is a rune Go does not allow in an identifier: drop it and let the next
			// character start a new word.
			upper = true
		}
	}
	out := b.String()
	if out == "" {
		return "portFn"
	}
	if out[0] >= '0' && out[0] <= '9' {
		return "port" + out
	}
	return out
}

// isGoIdent reports whether a name is already a legal Go identifier.
func isGoIdent(name string) bool {
	if name == "" {
		return false
	}
	for i, r := range name {
		switch {
		case r == '_':
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9':
			if i == 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}
