// Package shadow generates a drop-in module that calls the original and the Go port with the same
// arguments, compares the two answers, and returns the original's.
//
// This is the step between "the cases pass" and "I trust it in production": the cases are a sample, the
// shadow sees real traffic. It never changes behaviour on its own — a mismatch is recorded, the caller
// still gets what the original said.
package shadow

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Options is one shadow generation.
type Options struct {
	CrateDir string
	Unit     string
	Exports  []string
}

// module is the generated file: same names, original answers, mismatches on disk.
const module = `// Generated by go-anything: every call runs the original and the Go port and compares them.
//
//   const shr = require('./shadow.cjs')
//   shr.count('a b  ')      // the original's answer, always
//   shr.report()            // { calls, mismatches, byFunction }
//
// A mismatch is written to shadow.jsonl next to this file and reported once on stderr; the caller
// keeps getting the original's answer, so switching a unit into shadow mode cannot change behaviour.
const fs = require('node:fs')
const path = require('node:path')

const port = require(path.join(__dirname, 'index.cjs'))
const log = path.join(__dirname, 'shadow.jsonl')
const counters = { calls: 0, mismatches: 0, byFunction: {} }
let warned = 0

// canon sorts keys and spells the values JSON cannot carry, so the two answers compare as values.
const canon = v => {
  if (Array.isArray(v)) return '[' + v.map(canon).join(',') + ']'
  if (typeof v === 'number') {
    if (Number.isNaN(v)) return '"$NaN"'
    if (v === Infinity) return '"$Infinity"'
    if (v === -Infinity) return '"$-Infinity"'
    if (Object.is(v, -0)) return '"$-0"'
    return JSON.stringify(v)
  }
  if (typeof v === 'bigint') return JSON.stringify('$bigint:' + v.toString())
  if (v === undefined) return '"$undefined"'
  if (v && typeof v === 'object') {
    return '{' + Object.keys(v).sort().map(k => JSON.stringify(k) + ':' + canon(v[k])).join(',') + '}'
  }
  return JSON.stringify(v)
}

const note = (fn, args, want, got, why) => {
  counters.mismatches++
  counters.byFunction[fn] = (counters.byFunction[fn] || 0) + 1
  fs.appendFileSync(log, JSON.stringify({ at: new Date().toISOString(), fn, args, want, got, why }) + '\n')
  if (warned++ < 5) {
    console.error('go-anything shadow: ' + fn + ' differs (' + why + ')')
  }
}

const wrap = fn => (...args) => {
  counters.calls++
  const want = ORIGINAL[fn](...args)
  let got, threw
  try {
    got = port.callSync ? port.callSync(fn, ...args) : undefined
    if (!port.callSync) threw = 'the in-process addon is not built'
  } catch (e) {
    threw = String(e && e.message)
  }
  if (threw) {
    // The original answered, the port did not: that is a mismatch like any other.
    if (!(ORIGINAL_THROWS && ORIGINAL_THROWS[fn])) note(fn, args, want, undefined, threw)
  } else if (canon(want) !== canon(got)) {
    note(fn, args, want, got, 'the answers differ')
  }
  return want
}

const ORIGINAL = require(ORIGINAL_PATH)
const ORIGINAL_THROWS = null

const shadow = {}
for (const name of FUNCTIONS) {
  shadow[name] = wrap(name)
}
shadow.report = () => counters
shadow.reset = () => {
  counters.calls = 0
  counters.mismatches = 0
  counters.byFunction = {}
}
shadow.log = log
module.exports = shadow
`

// Run writes shadow.cjs into the crate folder.
func Run(opts Options) (string, error) {
	dir, err := filepath.Abs(opts.CrateDir)
	if err != nil {
		return "", err
	}
	if len(opts.Exports) == 0 {
		return "", fmt.Errorf("nothing to shadow: the crate carries no export")
	}
	if _, err := os.Stat(filepath.Join(dir, "index.cjs")); err != nil {
		return "", fmt.Errorf("run `go-anything bridge %s` first: %w", opts.CrateDir, err)
	}
	root, err := planRoot(dir, opts.Unit)
	if err != nil {
		return "", err
	}
	unitPath := filepath.Join(root, opts.Unit)
	rel, err := filepath.Rel(dir, unitPath)
	if err != nil {
		return "", err
	}
	names := make([]string, len(opts.Exports))
	for i, n := range opts.Exports {
		names[i] = fmt.Sprintf("%q", n)
	}
	text := strings.ReplaceAll(module, "ORIGINAL_PATH", fmt.Sprintf("%q", filepath.ToSlash(rel)))
	text = strings.ReplaceAll(text, "FUNCTIONS", "["+strings.Join(names, ", ")+"]")
	path := filepath.Join(dir, "shadow.cjs")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// Mismatch is one recorded difference.
type Mismatch struct {
	At   string          `json:"at"`
	Fn   string          `json:"fn"`
	Args []any           `json:"args"`
	Want json.RawMessage `json:"want"`
	Got  json.RawMessage `json:"got"`
	Why  string          `json:"why"`
}

// Report summarizes a shadow.jsonl.
type Report struct {
	Calls      int            `json:"calls"`
	Lines      int            `json:"lines"`
	ByFunction map[string]int `json:"byFunction"`
	First      []Mismatch     `json:"first"`
}

// ReadReport summarizes the shadow log, if there is one.
func ReadReport(crateDir string) (Report, error) {
	path := filepath.Join(crateDir, "shadow.jsonl")
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return Report{ByFunction: map[string]int{}}, nil
		}
		return Report{}, err
	}
	defer f.Close()
	out := Report{ByFunction: map[string]int{}}
	scan := bufio.NewScanner(f)
	scan.Buffer(make([]byte, 1<<20), 1<<20)
	for scan.Scan() {
		var m Mismatch
		if json.Unmarshal(scan.Bytes(), &m) != nil {
			continue
		}
		out.Lines++
		out.ByFunction[m.Fn]++
		if len(out.First) < 5 {
			out.First = append(out.First, m)
		}
	}
	return out, scan.Err()
}

// Markdown renders a report for a person.
func (r Report) Markdown() string {
	if r.Lines == 0 {
		return "No shadow mismatch recorded: every call this module saw agreed.\n"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%d mismatch(es) recorded", r.Lines)
	names := make([]string, 0, len(r.ByFunction))
	for name := range r.ByFunction {
		names = append(names, name)
	}
	sort.Strings(names)
	var parts []string
	for _, name := range names {
		parts = append(parts, fmt.Sprintf("%s ×%d", name, r.ByFunction[name]))
	}
	fmt.Fprintf(&b, ": %s\n\n", strings.Join(parts, ", "))
	b.WriteString("| Function | Arguments | Original | Port | Why |\n| --- | --- | --- | --- | --- |\n")
	for _, m := range r.First {
		args, _ := json.Marshal(m.Args)
		fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | `%s` | %s |\n", m.Fn, string(args),
			trim(m.Want), trim(m.Got), m.Why)
	}
	return b.String()
}

func trim(raw json.RawMessage) string {
	s := strings.TrimSpace(string(raw))
	s = strings.ReplaceAll(s, "|", "\\|")
	if len(s) > 60 {
		s = s[:60] + "…"
	}
	if s == "" {
		return "—"
	}
	return s
}

// planRoot walks up from the crate until the unit's file is under a parent.
func planRoot(crateDir, rel string) (string, error) {
	dir, err := filepath.Abs(crateDir)
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, rel)); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no folder above %s holds %s", crateDir, rel)
		}
		dir = parent
	}
}
