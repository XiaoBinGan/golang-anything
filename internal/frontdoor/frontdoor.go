// Package frontdoor scaffolds the Go binary that owns a program's entry point.
//
// `app record` proves it from the outside; the front door is how a port takes over inside. It dispatches
// on the recorded commands: a command that a wired unit answers runs the Go port, everything else runs
// the original binary with the same argv, stdin and environment. Every fallback is counted, so
// "how much is really Go" is a number and not a feeling — and `lift` only removes the fallback path
// when that number is zero.
package frontdoor

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/xiaobingan/go-anything/internal/app"
)

// Dir is where the front door lives, inside the repository.
const Dir = "go-app"

// Command is one recorded command and, once wired, the handler that answers it.
type Command struct {
	// Key is the argv after the program name, joined by spaces: what dispatch matches on.
	Key string `json:"key"`
	// Handler is a Go identifier in the front door; empty means the original answers.
	Handler string `json:"handler,omitempty"`
	// Unit is the crate whose registry holds the handler, for a person reading the file.
	Unit string `json:"unit,omitempty"`
}

// Options is one scaffold run.
type Options struct {
	Repo string
	// Original is the program to fall back to; taken from the recording's meta.json when empty.
	Original string
	Name     string
	Out      string
}

// Outcome lists what was written.
type Outcome struct {
	Dir      string    `json:"dir"`
	Module   string    `json:"module"`
	Original string    `json:"original"`
	Commands []Command `json:"commands"`
	Files    []string  `json:"files"`
	Notes    []string  `json:"notes,omitempty"`
}

// Scaffold writes the front door and returns what it laid out.
func Scaffold(opts Options) (Outcome, error) {
	repo, err := filepath.Abs(opts.Repo)
	if err != nil {
		return Outcome{}, err
	}
	evidence, err := app.Recorded(repo)
	if err != nil {
		return Outcome{}, err
	}
	if evidence.Original == "" && opts.Original == "" {
		return Outcome{}, fmt.Errorf("no original recorded: run `go-anything app record %s --command …` first, or pass --original", opts.Repo)
	}
	original := opts.Original
	if original == "" {
		original = evidence.Original
	}
	if original == "" {
		return Outcome{}, fmt.Errorf("the recording does not say which program it ran: pass --original")
	}
	out := opts.Out
	if out == "" {
		out = filepath.Join(repo, Dir)
	}
	if out, err = filepath.Abs(out); err != nil {
		return Outcome{}, err
	}
	name := opts.Name
	if name == "" {
		name = filepath.Base(repo)
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return Outcome{}, err
	}
	module := "example.com/" + strings.ReplaceAll(name, " ", "-") + "/go-app"
	if raw, err := os.ReadFile(filepath.Join(repo, "go.mod")); err == nil {
		if m := moduleOf(string(raw)); m != "" {
			rel, relErr := filepath.Rel(repo, out)
			if relErr == nil && !strings.HasPrefix(rel, "..") {
				module = m + "/" + filepath.ToSlash(rel)
			}
		}
	}

	var commands []Command
	argvs := map[string][]string{}
	seen := map[string]bool{}
	for _, c := range evidence.Cases {
		key := strings.Join(c.Argv, " ")
		if seen[key] {
			continue
		}
		seen[key] = true
		argvs[key] = c.Argv
		commands = append(commands, Command{Key: key})
	}
	sort.Slice(commands, func(i, j int) bool { return commands[i].Key < commands[j].Key })

	files := map[string]string{
		"go.mod":      fmt.Sprintf("module %s\n\ngo 1.24\n", module),
		"main.go":     mainGo(original, name),
		"commands.go": commandsGo(commands, argvs),
		"hooks.go":    hooksGo(),
		"README.md":   readme(name, original, len(commands)),
	}
	var written []string
	for rel, body := range files {
		path := filepath.Join(out, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return Outcome{}, err
		}
		// A person's handler file is never overwritten: the scaffold owns these five names only.
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			return Outcome{}, err
		}
		written = append(written, rel)
	}
	sort.Strings(written)
	return Outcome{Dir: out, Module: module, Original: original, Commands: commands, Files: written}, nil
}

// mainGo is the dispatcher: a wired command runs the port, anything else runs the original.
func mainGo(original, name string) string {
	return `// Command ` + name + ` is the Go front door: it owns the entry point and hands every command its
// port answers to Go, and everything else to the original.
//
// Generated by go-anything. ` + "`go-anything app wire`" + ` adds handlers; ` + "`go-anything app lift`" + `
// removes the fallback once nothing needs it.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"strings"
)

// original is the program the recording was made from: the fallback for every command no port answers.
const original = ` + fmt.Sprintf("%q", original) + `

func main() {
	argv := os.Args[1:]
	key := strings.Join(argv, " ")
	if h, ok := handlerFor(key); ok {
		// A wired command: the port answers the recorded invocation, and the exit code is ours.
		if err := h(recordedArgs(key)); err != nil {
			fmt.Fprintln(os.Stderr, "` + name + `: "+err.Error())
			os.Exit(1)
		}
		trace(key, false)
		return
	}
	// Everything else is the original's, byte for byte: same argv, same stdin, same environment.
	cmd := exec.Command(original, argv...)
	cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
	cmd.Env = os.Environ()
	trace(key, true)
	if err := cmd.Run(); err != nil {
		if ee, ok := err.(*exec.ExitError); ok {
			os.Exit(ee.ExitCode())
		}
		fmt.Fprintln(os.Stderr, "` + name + `: "+err.Error())
		os.Exit(1)
	}
}

// trace records which path a command took, for ` + "`go-anything app front-door --replay`" + ` to count.
// It writes only when GO_ANYTHING_TRACE names a file, so a normal run says nothing extra.
func trace(key string, fallback bool) {
	path := os.Getenv("GO_ANYTHING_TRACE")
	if path == "" {
		return
	}
	line, _ := json.Marshal(map[string]any{"command": key, "fallback": fallback})
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	fmt.Fprintln(f, string(line))
}

`
}

// commandsGo lists the recorded commands, and which of them a port answers.
func commandsGo(commands []Command, argvs map[string][]string) string {
	var b strings.Builder
	b.WriteString(`// Recorded commands and who answers them. ` + "`go-anything app wire`" + ` fills the handler in.
package main

// command is one recorded invocation: the argv a dispatch matches on, the recorded arguments a
// handler needs, and who answers it once wired.
type command struct {
	key     string
	argv    []string
	handler string
	unit    string
}

var commands = []command{
`)
	for _, c := range commands {
		var quoted []string
		for _, a := range argvs[c.Key] {
			quoted = append(quoted, fmt.Sprintf("%q", a))
		}
		fmt.Fprintf(&b, "\t{key: %q, argv: []string{%s}, handler: %q, unit: %q},\n",
			c.Key, strings.Join(quoted, ", "), c.Handler, c.Unit)
	}
	b.WriteString("}\n")
	return b.String()
}

// hooksGo is the registry the wire step adds to.
func hooksGo() string {
	return `// Registry of wired commands. ` + "`go-anything app wire`" + ` appends to this map; nothing else edits it.
package main

// handler answers one command with its recorded arguments.
type handler func(argv []string) error

var wired = map[string]handler{}

// handlerFor answers which handler a command has. It reads the registry at call time on purpose:
// package-level initialisers run before ` + "`init`" + `, and the wire step registers in an ` + "`init`" + `.
func handlerFor(key string) (handler, bool) {
	for _, c := range commands {
		if c.key != key || c.handler == "" {
			continue
		}
		h, ok := wired[key]
		return h, ok
	}
	return nil, false
}

// recordedArgs is what a handler gets: the recorded argv without its own words at the front.
func recordedArgs(key string) []string {
	for _, c := range commands {
		if c.key == key && len(c.argv) > 1 {
			return c.argv[1:]
		}
	}
	return nil
}
`
}

func readme(name, original string, commands int) string {
	return fmt.Sprintf(`# %s front door

A Go binary that owns the entry point of `+"`%s`"+`.

- %d commands were recorded by `+"`go-anything app record`"+`.
- A command a wired port answers runs in Go; everything else runs the original, unchanged.
- `+"`go-anything app wire`"+` connects a port to a command; `+"`go-anything app lift`"+` removes the
  fallback once nothing needs it.

    go build -o %s .
    ./%s --help

Set `+"`GO_ANYTHING_TRACE=/tmp/trace.jsonl`"+` to see which path each command took.
`, name, original, commands, name, name)
}

// Wire connects a command to a handler that a crate provides.
func Wire(frontDoor, key, handlerName, unit string, portModule, portFunc string) (string, error) {
	dir, err := filepath.Abs(frontDoor)
	if err != nil {
		return "", err
	}
	path := filepath.Join(dir, "hooks_wired.go")
	existing := ""
	if raw, err := os.ReadFile(path); err == nil {
		existing = string(raw)
	}
	// Dispatch reads `commands`, so wiring rewrites that table's handler column as well.
	commandsPath := filepath.Join(dir, "commands.go")
	raw, err := os.ReadFile(commandsPath)
	if err != nil {
		return "", fmt.Errorf("%s: not a front door", frontDoor)
	}
	updated := setHandler(string(raw), key, handlerName, unit)
	if updated == string(raw) {
		return "", fmt.Errorf("no recorded command %q in %s: run `go-anything app record` for it first", key, frontDoor)
	}
	if err := os.WriteFile(commandsPath, []byte(updated), 0o644); err != nil {
		return "", err
	}
	body := wireGo(existing, key, handlerName, portModule, portFunc)
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// setHandler fills in the handler of one table row, and nothing else: the row also carries the
// recorded argv, and dropping it would leave a handler with no arguments.
func setHandler(text, key, handlerName, unit string) string {
	lines := strings.Split(text, "\n")
	for i, line := range lines {
		if !strings.Contains(line, fmt.Sprintf("{key: %q,", key)) {
			continue
		}
		updated := strings.Replace(line, `handler: ""`, fmt.Sprintf("handler: %q", handlerName), 1)
		updated = strings.Replace(updated, `unit: ""`, fmt.Sprintf("unit: %q", unit), 1)
		lines[i] = updated
		return strings.Join(lines, "\n")
	}
	return text
}

// wireGo keeps every previous wiring and adds this one: a front door grows a command at a time.
func wireGo(existing, key, handlerName, portModule, portFunc string) string {
	header := "// Wired commands: generated by `go-anything app wire`.\npackage main\n\n" +
		"import (\n\t\"fmt\"\n\n\tportstore " + fmt.Sprintf("%q", portModule) + "\n)\n\nfunc init() {\n"
	body := existing
	if body == "" || !strings.Contains(body, "portstore") {
		body = header
	}
	// Drop the closing brace of the init block, append the new wiring, and close it again.
	body = strings.TrimSuffix(strings.TrimRight(body, "\n"), "}")
	body = strings.TrimRight(body, "\n") + "\n"
	body += fmt.Sprintf("\t// %s\n", handlerName)
	body += fmt.Sprintf("\twired[%q] = func(argv []string) error {\n", key)
	body += "\t\targs := make([]any, 0, len(argv))\n"
	body += "\t\tfor _, a := range argv {\n\t\t\targs = append(args, a)\n\t\t}\n"
	body += fmt.Sprintf("\t\tout, err := portstore.Call(%q, args)\n", strings.TrimSpace(portFunc))
	body += "\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n"
	body += "\t\tfmt.Println(out)\n\t\treturn nil\n\t}\n}\n"
	return body
}

// CanLift says whether the fallback path can go: every recorded command must be wired.
func CanLift(frontDoor string) (bool, int, int, error) {
	dir, err := filepath.Abs(frontDoor)
	if err != nil {
		return false, 0, 0, err
	}
	raw, err := os.ReadFile(filepath.Join(dir, "commands.go"))
	if err != nil {
		return false, 0, 0, fmt.Errorf("%s: not a front door", frontDoor)
	}
	total, wired := 0, 0
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.Contains(line, "{key: ") {
			continue
		}
		total++
		if !strings.Contains(line, `handler: ""`) {
			wired++
		}
	}
	return total > 0 && wired == total, wired, total, nil
}

// Lift removes the fallback: the front door stops carrying the original.
func Lift(frontDoor string) (string, error) {
	ok, wired, total, err := CanLift(frontDoor)
	if err != nil {
		return "", err
	}
	if !ok {
		return "", fmt.Errorf("%d of %d commands are wired: wire the rest, or keep the fallback", wired, total)
	}
	dir, err := filepath.Abs(frontDoor)
	if err != nil {
		return "", err
	}
	path := filepath.Join(dir, "main.go")
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	if strings.Contains(string(raw), "lifted") {
		return path, nil
	}
	text := liftMain(string(raw))
	if text == string(raw) {
		return "", fmt.Errorf("could not find the fallback in %s", path)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// liftMain replaces the fallback body with a refusal, and keeps the trace for the record.
func liftMain(text string) string {
	start := strings.Index(text, "\t// Everything else is the original's")
	end := strings.Index(text, "\n}\n\n// trace records")
	if start < 0 || end < 0 || end < start {
		return text
	}
	replacement := `	// lifted: every recorded command runs in Go, so the original is no longer carried.
	fmt.Fprintf(os.Stderr, "go-anything: nothing answers %q; this build was lifted and runs no fallback\n", key)
	trace(key, true)
	os.Exit(1)`
	lifted := text[:start] + replacement + text[end:]
	// The fallback was the only user of os/exec: leaving the import breaks the build.
	lifted = strings.Replace(lifted, "\t\"os/exec\"\n", "", 1)
	return lifted
}

// moduleOf reads the module path from a go.mod.
func moduleOf(text string) string {
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "module ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "module "))
		}
	}
	return ""
}
